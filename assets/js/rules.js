(function () {
  const N = window.N = window.N || {};
  N.rules = N.rules || {};

  /**
   * Дошел ли разговор до стадии договора, то есть пора ли ИИ звать менеджера.
   * Вызывается после каждого сообщения клиента, в демо-режиме и с Claude API.
   *
   * s — сигналы, которые ИИ собрал по диалогу:
   *   s.contractWords  клиент написал «договор», «счет», «shartnoma», «invoice» и т.п.
   *                    (в режиме Claude API это решение модели contract_ready)
   *   s.kpAsked        просит коммерческое предложение
   *   s.hasItems       в карточке есть товары или услуги
   *   s.hasQty         хотя бы у одного товара клиент назвал количество
   *   s.hasPhone       есть телефон (в WhatsApp он известен сразу)
   *   s.hasCompany     есть название компании или ИНН/STIR
   *   s.sum            сумма заявки в $
   *   s.clientMsgs     сколько сообщений написал клиент
   *
   * Вернуть true, если ИИ должен передать диалог менеджеру как «готов к договору».
   */
  N.rules.isContractStage = (s) => {
    // TODO(NEC): уточнить правило под процесс продаж.
    // Сейчас: клиент сам заговорил о договоре или счете и уже понятно, что он берет.
    return s.contractWords && s.hasItems;
  };
})();
